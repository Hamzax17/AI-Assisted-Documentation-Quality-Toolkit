def md(s: str):
    return parse(textwrap.dedent(s).lstrip("\n"), "doc.md", "doc.md")


def rules(issues):
    return [i.rule for i in issues]


# ---- reader ---------------------------------------------------------------
def test_reader_headings_slugs_and_duplicates():
    d = md("""
        # Title
        ## Set-up & Go!
        ## Set-up & Go!
        """)
    assert [h.level for h in d.headings] == [1, 2, 2]
    assert d.headings[1].slug == "set-up--go"
    assert d.headings[2].slug == "set-up--go-1"
    assert slugify("`code` Heading") == "code-heading"


def test_reader_ignores_code_frontmatter_comments():
    d = md("""
        ---
        title: T
        ---
        # H
        <!-- [hidden](nope.md) -->
        ```python
        # not a heading
        [x](nothere.md)
        ```
        Real [link](a.md) and `[inline](b.md)`.
        """)
    assert [h.text for h in d.headings] == ["H"]
    assert [l.target for l in d.links] == ["a.md"]
    assert d.meta["title"] == "T"
    assert d.code_blocks[0].lang == "python"


def test_reader_link_kinds():
    d = md("""
        # T
        [a](x.md) ![img](i.png) <https://e.com/a> see https://e.com/b.
        [r][lbl] <a href="h.html">h</a>

        [lbl]: https://e.com/c
        """)
    kinds = {(l.kind, l.target) for l in d.links}
    assert ("inline", "x.md") in kinds
    assert ("autolink", "https://e.com/a") in kinds
    assert ("bare", "https://e.com/b") in kinds
    assert ("ref_use", "lbl") in kinds
    assert ("html", "h.html") in kinds
    assert ("ref_def", "https://e.com/c") in kinds


# ---- links ----------------------------------------------------------------
def test_internal_links_and_anchors(tmp_path: Path):
    (tmp_path / "a.md").write_text("# A\n\n[ok](b.md#target) [bad file](nope.md) [bad anchor](b.md#nothing) [self](#a) [bad self](#zzz)\n")
    (tmp_path / "b.md").write_text("# B\n\n## Target\n")
    d = load(tmp_path / "a.md", tmp_path)
    issues = check_links(d, tmp_path)
    assert rules(issues) == ["broken-link", "broken-anchor", "broken-anchor"]


def test_broken_link_suggests_close_name(tmp_path: Path):
    (tmp_path / "guide.md").write_text("# G\n")
    (tmp_path / "a.md").write_text("[x](gide.md)\n")
    issues = check_links(load(tmp_path / "a.md", tmp_path), tmp_path)
    assert "guide.md" in issues[0].suggestion


def test_undefined_reference_and_empty(tmp_path: Path):
    (tmp_path / "a.md").write_text("[x][nope] [y]()\n")
    issues = check_links(load(tmp_path / "a.md", tmp_path), tmp_path)
    assert sorted(rules(issues)) == ["empty-link", "undefined-reference"]


class FakeChecker(ExternalChecker):
    def _fetch(self, url):
        return {"https://ok.com": (200, None), "https://gone.com": (404, None),
                "https://slow.com": (None, "timed out"), "https://wall.com": (403, None)}[url]


def test_external_links(tmp_path: Path):
    (tmp_path / "a.md").write_text("[1](https://ok.com) [2](https://gone.com) [3](https://slow.com) [4](https://wall.com)\n")
    d = load(tmp_path / "a.md", tmp_path)
    ext = FakeChecker()
    ext.prefetch(l.target for l in d.links)
    issues = check_links(d, tmp_path, ext)
    assert [(i.rule, i.severity) for i in issues] == [
        ("broken-link", "error"), ("unreachable-link", "warning"), ("link-access-limited", "warning")]
    assert check_links(d, tmp_path, None) == []  # offline by default


# ---- style ----------------------------------------------------------------
def test_style_rules():
    d = md("""
        # Title

        This is the the end. The token is generated by the server. It is really simple to utilize this.
        TODO finish this.

        ![](a.png) [click here](x.md)

        ```
        code
        ```
        """)
    got = set(rules(check_style(d)))
    assert {"repeated-word", "passive-voice", "weasel-word", "wordy-phrase", "placeholder-text",
            "missing-alt-text", "generic-link-text", "code-fence-language"} <= got


def test_long_sentence_threshold():
    long = " ".join(["word"] * 35) + "."
    assert "long-sentence" in rules(check_style(md(f"# T\n\n{long}\n")))
    assert "long-sentence" not in rules(check_style(md(f"# T\n\n{long}\n"), {"max_sentence_words": 40}))


def test_style_ignores_code_and_clean_text():
    d = md("""
        # Title

        Run `the the` and `is really done` to start the service.
        """)
    assert check_style(d) == []


def test_heading_structure():
    d = md("# A\n\n#### Deep\n\ntext\n\n# B\n")
    got = rules(check_style(d))
    assert "heading-level-skip" in got and "multiple-h1" in got


def test_unclosed_fence():
    assert "unclosed-code-fence" in rules(check_style(md("# T\n\n```py\nx = 1\n")))


def test_issue_line_numbers():
    d = md("# T\n\nfine line\nsecond line is really bad\n")
    weasel = [i for i in check_style(d) if i.rule == "weasel-word"][0]
    assert weasel.line == 4


# ---- terminology ----------------------------------------------------------
def test_terminology_flags_variants_but_not_code_or_urls():
    g = load_glossary()
    d = md("""
        # T

        Host it on Github. Our API is great. The api is not. Email us, or e-mail us.
        See github.com/foo and `Github` and [x](https://github.com/y).
        """)
    issues, usage = check_terminology(d, g)
    flagged = sorted(i.message.split('"')[3] for i in issues)
    assert flagged == ["Github", "api", "e-mail"]
    assert usage["GitHub"]["variants"] == {"Github": 1}


