# ---- sections -------------------------------------------------------------
def test_readme_profile_missing_sections():
    d = parse("# P\n\nSome text " + "word " * 40 + "\n\n## Usage\n\nrun it\n", "README.md", "README.md")
    issues = check_sections(d, load_sections())
    missing = [i for i in issues if i.rule == "missing-section"]
    assert len(missing) == 4  # Installation, License (required); Contributing, Features (recommended)
    assert {i.severity for i in missing} == {"warning", "info"}
    assert any("License" in i.message for i in missing)


def test_frontmatter_doc_type_and_empty_section_and_title():
    d = parse("---\ndoc_type: api\n---\n## Overview\n\n## Parameters\n\nx\n", "x.md", "x.md")
    got = check_sections(d, load_sections())
    assert "missing-title" in rules(got)
    assert "empty-section" in rules(got)  # Overview has no body and next heading is same level
    assert any("Returns" in i.message for i in got)


def test_parent_heading_without_body_is_ok():
    d = md("# T\n\n## Parent\n\n### Child\n\ntext\n")
    assert "empty-section" not in rules(check_sections(d, {"require_h1": True}))


