def test_parse_json_array_variants():
    assert _parse_json_array('```json\n[{"id": 0, "rewrite": "x"}]\n```')[0]["id"] == 0
    assert _parse_json_array('Sure! [{"id": 1, "rewrite": "y"}] done')[0]["id"] == 1
    with pytest.raises(ProviderError):
        _parse_json_array("no json here")


def test_mock_rewrite_end_to_end_and_protection():
    g = load_glossary()
    d = md("# T\n\nIt is really easy to utilize `Github` here on Github, see [Github](https://github.com/x).\n")
    issues = check_style(d) + check_terminology(d, g)[0]
    out = build_rewrites(issues, MockProvider(glossary=g), ["GitHub"])
    assert len(out) == 1
    r = out[0]
    assert "utilize" not in r["rewrite"] and "use" in r["rewrite"]
    assert "`Github`" in r["rewrite"] and "https://github.com/x" in r["rewrite"]
    assert r["rewrite"].count("GitHub") == 2  # prose + link text fixed; code/URL protected
    assert r["warnings"] == []


def test_rewrite_flags_dropped_code():
    class Bad(MockProvider):
        def rewrite(self, items, terms):
            return {it["id"]: "Totally different text." for it in items}

    d = md("# T\n\nIt is really easy to run `acme init` today.\n")
    out = build_rewrites(check_style(d), Bad(), [])
    assert out and "`acme init`" in out[0]["warnings"][0]


def test_provider_selection(monkeypatch):
    for k in ("GEMINI_API_KEY", "ANTHROPIC_API_KEY", "DOCQ_PROVIDER"):
        monkeypatch.delenv(k, raising=False)
    with pytest.raises(ProviderError):
        get_provider()
    monkeypatch.setenv("GEMINI_API_KEY", "k")
    assert get_provider().name == "gemini"
    assert get_provider("anthropic").name == "anthropic"
    with pytest.raises(ProviderError):
        get_provider("bogus")


# ---- report ---------------------------------------------------------------
def test_score_and_reports():
    d = md("# T\n\nThis is really it. [x](nope.md)\n")
    issues = check_style(d)
    assert score([], 100) == 100
    assert score(issues, 100) < 100
    rep = build_report([{"file": "doc.md", "words": d.words, "issues": issues}])
    assert rep["summary"]["files"] == 1
    json.dumps(rep)
    text = to_markdown(rep)
    assert "# Documentation Quality Report" in text and "`weasel-word`" in text


