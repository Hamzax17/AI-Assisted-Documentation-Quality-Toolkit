EXAMPLES = Path(__file__).resolve().parent.parent / "examples" / "docs"


def test_cli_on_examples(tmp_path, capsys):
    j, m = tmp_path / "r.json", tmp_path / "r.md"
    code = cli.main([str(EXAMPLES), "--json", str(j), "--markdown", str(m), "--rewrite", "--provider", "mock"])
    out = capsys.readouterr().out
    assert code == 1  # broken links are errors
    rep = json.loads(j.read_text())
    assert rep["summary"]["by_severity"]["error"] >= 4
    assert {"links", "style", "terminology", "sections"} <= set(rep["summary"]["by_check"])
    assert rep["rewrites"]
    assert "AI-assisted rewrite suggestions" in m.read_text()
    assert "guide.md" in out


def test_cli_exit_codes_and_options(tmp_path, capsys):
    good = tmp_path / "ok.md"
    good.write_text("# Title\n\n" + "A clear short sentence about the product. " * 5 + "\n")
    assert cli.main([str(good), "--quiet"]) == 0
    assert cli.main([str(good), "--quiet", "--fail-under", "101"]) == 1
    assert cli.main([str(tmp_path / "missing.md")]) == 2
    assert cli.main([str(good), "--rewrite"]) in (0, 2)  # 2 when no API key is set
    bad = tmp_path / "bad.md"
    bad.write_text("# T\n\n[x](nope.md)\n")
    assert cli.main([str(bad), "--quiet"]) == 1
    assert cli.main([str(bad), "--quiet", "--disable", "broken-link", "--disable", "too-short"]) == 0


def test_cli_config_file_and_ignore(tmp_path, capsys):
    (tmp_path / "a.md").write_text("# T\n\n[x](nope.md)\n")
    (tmp_path / "skip.md").write_text("# T\n\n[x](nope.md)\n")
    cfg = tmp_path / "doccheck.json"
    cfg.write_text(json.dumps({"ignore": ["skip.md"], "disable": ["too-short"]}))
    cli.main([str(tmp_path), "--config", str(cfg)])
    out = capsys.readouterr().out
    assert "a.md" in out and "skip.md" not in out and "too-short" not in out
